import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, posix } from 'node:path'

/**
 * Emits a service worker and an asset manifest so the game can be installed
 * to a phone's home screen and played with no network at all.
 *
 * Two layers, deliberately:
 *  - The shell (html/js/css/icons/UI sprites) is precached on install, so the
 *    game always starts offline.
 *  - The ~54 MB of models, audio and skyboxes is NOT precached silently. A
 *    54 MB background download nobody asked for is hostile on mobile data, so
 *    it is cached on demand as worlds are played, and the title screen offers
 *    an explicit "Make it work offline" button that fetches the lot with a
 *    progress bar.
 */
export function offlinePlugin({ cacheName = 'ccc' } = {}) {
  let outDir = 'dist'
  let base = '/'
  return {
    name: 'ccc-offline',
    apply: 'build',
    configResolved(cfg) {
      outDir = cfg.build.outDir
      base = cfg.base || '/'
    },
    closeBundle() {
      const root = join(process.cwd(), outDir)

      const walk = (dir) => {
        const out = []
        for (const name of readdirSync(dir)) {
          const full = join(dir, name)
          const st = statSync(full)
          if (st.isDirectory()) out.push(...walk(full))
          else out.push({ url: posix.join(...relative(root, full).split(/[\\/]/)), size: st.size })
        }
        return out
      }

      const files = walk(root).filter((f) => f.url !== 'sw.js' && f.url !== 'asset-manifest.json')
      const isShell = (u) =>
        u === 'index.html' || u.startsWith('assets/index-') ||
        u.startsWith('icons/') || u.startsWith('assets/ui/') || u === 'manifest.webmanifest'

      const shell = files.filter((f) => isShell(f.url)).map((f) => f.url)
      const rest = files.filter((f) => !isShell(f.url))
      const version = String(Date.now())

      writeFileSync(join(root, 'asset-manifest.json'), JSON.stringify({
        version,
        totalBytes: files.reduce((n, f) => n + f.size, 0),
        shell,
        assets: rest.map((f) => f.url),
        assetBytes: rest.reduce((n, f) => n + f.size, 0),
      }))

      writeFileSync(join(root, 'sw.js'), serviceWorker({ cacheName, version, base, shell }))
      // eslint-disable-next-line no-console
      console.log(`  offline: shell ${shell.length} files, ${rest.length} assets ` +
        `(${(rest.reduce((n, f) => n + f.size, 0) / 1048576).toFixed(0)} MB on demand)`)
    },
  }
}

const serviceWorker = ({ cacheName, version, base, shell }) => `/* generated by tools/vite-plugin-offline.js */
const CACHE = '${cacheName}-${version}'
const BASE = '${base}'
const SHELL = ${JSON.stringify(shell)}

self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE)
    // Individually, so one 404 cannot fail the whole install.
    await Promise.all(SHELL.map((u) => c.add(new Request(BASE + u, { cache: 'reload' })).catch(() => {})))
    self.skipWaiting()
  })())
})

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE) await caches.delete(k)
    await self.clients.claim()
  })())
})

self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== location.origin) return

  // Navigations fall back to the cached shell so launching offline works.
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      try { return await fetch(req) }
      catch { return (await caches.match(BASE + 'index.html')) ?? Response.error() }
    })())
    return
  }

  // Everything else is cache-first: assets are immutable per build.
  e.respondWith((async () => {
    const hit = await caches.match(req, { ignoreSearch: true })
    if (hit) return hit
    try {
      const res = await fetch(req)
      if (res.ok) (await caches.open(CACHE)).put(req, res.clone())
      return res
    } catch (err) {
      return new Response('offline', { status: 503 })
    }
  })())
})

// The explicit "download everything" path, driven from the title screen.
self.addEventListener('message', (e) => {
  if (e.data?.type !== 'PRECACHE_ALL') return
  e.waitUntil((async () => {
    const client = e.source
    const send = (m) => client?.postMessage(m)
    try {
      const manifest = await (await fetch(BASE + 'asset-manifest.json', { cache: 'reload' })).json()
      const cache = await caches.open(CACHE)
      const urls = [...manifest.shell, ...manifest.assets]
      let done = 0
      const BATCH = 6
      for (let i = 0; i < urls.length; i += BATCH) {
        await Promise.all(urls.slice(i, i + BATCH).map(async (u) => {
          const req = new Request(BASE + u)
          if (!(await cache.match(req))) {
            try {
              const res = await fetch(req)
              if (res.ok) await cache.put(req, res)
            } catch {}
          }
          done++
        }))
        send({ type: 'PRECACHE_PROGRESS', done, total: urls.length })
      }
      send({ type: 'PRECACHE_DONE', total: urls.length })
    } catch (err) {
      send({ type: 'PRECACHE_FAILED', error: String(err) })
    }
  })())
})
`
